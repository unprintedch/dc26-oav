<div class="wp-block-accordion-item"><!-- wp:accordion-heading -->
<h3 class="wp-block-accordion-heading"><button type="button" class="wp-block-accordion-heading__toggle"><span class="wp-block-accordion-heading__toggle-title">Le Conseil de l’Ordre</span><span class="wp-block-accordion-heading__toggle-icon" aria-hidden="true">+</span></button></h3>
<!-- /wp:accordion-heading -->

<!-- wp:accordion-panel -->
<div role="region" class="wp-block-accordion-panel"><!-- wp:paragraph -->
<p>Le Conseil de l’Ordre est l’organe exécutif de l’association professionnelle.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Il est présidé par le Bâtonnier. Le Conseil de l'Ordre compte sept membres et il est soutenu dans ses efforts par un ou une Secrétaire générale.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Le Bâtonnier règle toutes les affaires qui n’appellent pas une décision d’un autre organe de l’association. L’une de ses tâches principales est de s’efforcer de régler les conflits entre les membres de l’Ordre et entre ceux-ci et des tiers, généralement des clients. Il lui appartient également, lorsque les faits le justifient, de saisir les organes disciplinaires compétents (Commission de discipline ou/et Chambre des avocats).</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Le Conseil de l’Ordre rencontre régulièrement les différentes autorités judiciaires et autres associations professionnelles en relation avec le monde judiciaire (Association des notaires vaudois, Ordre des avocats de Genève, par exemple).</p>
