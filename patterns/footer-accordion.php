<h3 class="wp-block-accordion-heading"><button type="button" class="wp-block-accordion-heading__toggle"><span class="wp-block-accordion-heading__toggle-title">Le Bâtonnier</span><span class="wp-block-accordion-heading__toggle-icon" aria-hidden="true">+</span></button></h3>
<!-- /wp:accordion-heading -->

<!-- wp:accordion-panel -->
<div role="region" class="wp-block-accordion-panel"><!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>Le Bâtonnier est le Primus inter pares (premier parmi les siens) des avocats.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Elu pour deux ans par l’Assemblée générale, il préside l’Ordre et son Conseil.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Il est à ce titre le premier gardien du respect par les avocats des règles éthiques, déontologiques, statutaires ou légales.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Il conseille et, au besoin, arbitre lors de conflits entre confrères ou entre un client et son avocat.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Il est également le représentant et le porte-parole de la profession auprès des autorités judiciaires, administratives ou politiques, tout comme auprès du public.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li>Il participe au rayonnement de l’OAV en Suisse et à l’étranger, notamment auprès des autres Barreaux.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

