<h3 class="wp-block-accordion-heading"><button type="button" class="wp-block-accordion-heading__toggle"><span class="wp-block-accordion-heading__toggle-title">La Chambre de médiation</span><span class="wp-block-accordion-heading__toggle-icon" aria-hidden="true">+</span></button></h3>
<!-- /wp:accordion-heading -->

<!-- wp:accordion-panel -->
<div role="region" class="wp-block-accordion-panel"><!-- wp:paragraph -->
<p>La Chambre de médiation met à disposition du public une structure favorisant le recours à la médiation dans tous les domaines du droit. Ses membres sont des médiateurs formés et certifiés par la FSA (Fédération Suisse des Avocats) et qui peuvent intervenir dans le cadre de litiges familiaux, commerciaux et pénaux, etc.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>La Chambre de médiation peut vous donner des informations sur la médiation et son utilité dans des cas concrets, sur le processus de médiation, le rôle du médiateur, des parties et des avocats conseils dans le cadre de la médiation.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>La Chambre de médiation peut également organiser la médiation depuis la phase initiale de recherche d'un médiateur jusqu'à la fin du processus, en mettant à votre disposition le contrat de médiation, les locaux où se déroulent la médiation et, bien sûr, un médiateur professionnellement qualifié.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Le site de la Chambre de médiation : <a href="http://www.mediation-oav.ch/">http://www.mediation-oav.ch/</a></p>
